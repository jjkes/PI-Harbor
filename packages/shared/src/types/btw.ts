import type { AppError } from "../errors.js";
import type { MessageUsage } from "./messages.js";

/**
 * BTW side questions (ADR 0344): a read-only question about a main session,
 * answered from a snapshot of that session's model-visible context. A BTW run
 * never writes to the main session.
 */

/** One earlier exchange of a BTW thread, sent back as quoted conversation. */
export type BtwHistoryTurn = { question: string; answer: string };

/** Renderer to Electron Main: ask one side question about a main session. */
export type BtwAskRequest = {
  /** The main session the question is about. */
  sessionId: string;
  /** Generated by the renderer; also namespaces the run's host tool-call ids. */
  runId: string;
  question: string;
  /** Earlier turns of this thread, oldest first. Untrusted text. */
  history: BtwHistoryTurn[];
};

export type BtwAskResult = { accepted: true };

export type BtwAbortRequest = { runId: string };

/**
 * Events of one BTW run. A run emits `started` at most once, then deltas,
 * tool rows, and usage reports, and ends with exactly one `done` or `error`.
 * An `error` after text keeps that text as a partial answer.
 */
export type BtwEvent =
  | {
      type: "started";
      providerId: string;
      modelId: string;
      /** Whether a main turn was running when the snapshot was taken. */
      mainTurnRunning: boolean;
    }
  | { type: "text_delta"; delta: string }
  | { type: "tool_start"; toolCallId: string; toolName: string; args: unknown }
  | { type: "tool_end"; toolCallId: string; ok: boolean; errorCode?: string }
  | { type: "usage"; usage: MessageUsage }
  | { type: "done"; stopReason: "stop" | "aborted" }
  | { type: "error"; error: AppError };

export type BtwEventEnvelope = {
  runId: string;
  sessionId: string;
  /** Per-run sequence number, starting at 0. */
  seq: number;
  event: BtwEvent;
};
